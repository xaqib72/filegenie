    {
        return self::$tools[$id] ?? null;
    }

    public static function byCategory(string $category): array
    {
        return array_filter(self::$tools, fn($t) => $t['category'] === $category);
    }

    public static function byEngine(string $engine): array
    {
        return array_filter(self::$tools, fn($t) => $t['processing_engine'] === $engine);
    }

    public static function count(): int
    {
        return count(self::$tools);
    }

    public static function search(string $query): array
    {
        $q = strtolower(trim($query));
        if ($q === '') {
            return [];
        }
        $results = [];
        foreach (self::$tools as $tool) {
            $haystack = strtolower(implode(' ', array_merge(
                [$tool['name'], $tool['short_description']],
                $tool['keywords'] ?? [],
                $tool['search_aliases'] ?? []
            )));
            if (str_contains($haystack, $q)) {
                $results[] = $tool;
            } elseif (isset($tool['related_tools']) && is_array($tool['related_tools'])) {
                // light alias match
                if (str_contains($q, strtolower($tool['name']))) {
                    $results[] = $tool;
                }
            }
        }
        return $results;
    }
